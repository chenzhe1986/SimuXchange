//! 深圳统一网关（sz）：深交所 Binary 协议（Ver1.32）的全套实现。
//!
//! 已覆盖规范 4.5 节“委托申报”全部消息类型：
//! - 4.5.1 新订单（1xxx01）：28 种业务消息类型（表 3-3），
//!   按 4.5.1.x 小节顺序组织（现货竞价/债券回购/期权竞价/协议交易/
//!   盘后定价大宗/转融通出借/债券转股回售/期权行权/基金申赎/要约收购/
//!   转处置/垫券还券/待清偿扣划/港股通/备兑互转/盘后定价/债券现券/
//!   跨银行间 ETF/ETF 实时申赎等）
//! - 4.5.2 撤单请求（190007）/ 4.5.3 撤单失败（290008）：各业务共用
//! - 4.5.4 订单响应及撤单成功执行报告（2xxx02）：24 种业务报文
//! - 4.5.5 成交执行报告（2xxx15）：11 种业务报文
//!
//! 业务差异点（strategy::BizInfo 表驱动）：
//! - 仅现货集中竞价（010）支持部分成交，其余业务部分成交类策略自动降级
//! - 表 3-4 无成交回报的业务（ETF 申赎/认购/行权/质押解押等）只回确认，
//!   手动回复成交会被拒绝
//!
//! 目录内各模块职责：
//! - protocol：报文编解码（结构体 ↔ 字节串，8 字节报文头 + 校验和）
//! - session：TCP 会话生命周期（Logon/心跳/28 种新订单分发/按业务撤单/手动回报）
//! - strategy：业务特征表 + 模拟回报策略（收到委托后生成回报计划）

pub mod protocol;
pub mod session;
pub mod strategy;
